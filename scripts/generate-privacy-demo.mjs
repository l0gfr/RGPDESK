// Generate fixed fictional Astro markup, never browser data or imported HTML.
// Unit tests compare each checked-in page with the canonical renderer output.
import { build } from "esbuild";
import { mkdtemp, readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
const temp = await mkdtemp(join(tmpdir(), "rgpdesk-demo-"));
try {
  const bundle = join(temp, "reports.mjs");
  await build({entryPoints:["apps/web/src/features/privacy/demo-reports.ts"], outfile:bundle, bundle:true, platform:"node", format:"esm", logLevel:"silent"});
  const { buildDemoReports, demoReportParts } = await import(pathToFileURL(bundle).href);
  const navStyle = await readFile("apps/web/src/features/privacy/assets/demo-report-navigation.css", "utf8");
  for (const report of await buildDemoReports()) {
    if (!["registre","sous-traitance","aipd"].includes(report.slug)) throw new Error("Unexpected demo route");
    const { body, style } = demoReportParts(report.html);
    // Astro expressions must never enter generated literal markup.
    if (/[{}]/.test(body) || /[<>&"{}]/.test(report.title)) throw new Error("Unexpected fictional markup");
    const folder = join("apps/web/src/pages/app/privacy/demo",report.slug);
    const type = report.slug === "aipd" ? "pia" : "register";
    await writeFile(`apps/web/src/features/privacy/assets/demo-report-${type}.css`,style);
    const root = "../../../../../features/privacy/assets/";
    const nav = [["registre","Registre responsable"],["sous-traitance","Sous-traitance"],["aipd","AIPD"]].map(([slug,title]) => `<a${slug===report.slug?' aria-current="page"':""} href="/app/privacy/demo/${slug}/">${title}</a>`).join("");
    const page = `---
// Generated by scripts/generate-privacy-demo.mjs from fictional data only.
import ReportPrintButton from "../../../../../features/privacy/components/ReportPrintButton.astro";
import reportStyle from "${root}demo-report-${type}.css?url";
import readingStyle from "${root}demo-report-readable.css?url";
import favicon from "${root}rgpdesk-symbol.svg?url";
---
<!doctype html>
<html lang="fr"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /><meta name="referrer" content="no-referrer" /><meta name="robots" content="noindex, nofollow" /><link rel="icon" href={favicon} type="image/svg+xml" /><title>RGPDESK | Démonstration · ${report.title}</title><link rel="stylesheet" href={reportStyle} /><link rel="stylesheet" href={readingStyle} /></head>
<body><aside class="sample-report-navigation" aria-label="Navigation du dossier de démonstration"><a href="/app/privacy/demo/">← Le dossier complet</a><nav aria-label="Documents du dossier">${nav}</nav><ReportPrintButton /></aside>
${body}
</body></html>
<style is:global>${navStyle}</style>
`;
    await mkdir(folder,{recursive:true});
    await writeFile(join(folder,"index.astro"),page);
  }
} finally { await rm(temp,{recursive:true,force:true}); }
