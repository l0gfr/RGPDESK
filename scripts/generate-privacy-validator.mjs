import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

for (const [name, version] of [["master", 1], ["backup", 1], ["master", 2], ["master", 3], ["master", 4], ["share", 1], ["manifest", 1], ["backup", 2]]) {
  const schema = JSON.parse(await readFile(`packages/privacy-core/schemas/rgpd-${name}-v${version}.schema.json`, "utf8"));
  const ajv = new Ajv2020({ strict: true, allErrors: false, code: { source: true, esm: true } });
  addFormats(ajv);
  const result = await build({
    bundle: true, format: "esm", legalComments: "none", platform: "browser", target: "es2022", write: false,
    stdin: { contents: standaloneCode(ajv, ajv.compile(schema)), loader: "js", resolveDir: process.cwd(), sourcefile: `${name}-validator.generated.js` },
  });
  const output = `// Generated by scripts/generate-privacy-validator.mjs. Do not edit manually.\n${result.outputFiles[0].text}`;
  const path = `packages/privacy-core/src/generated/${name}${version === 1 ? "" : "-v" + version}-validator.js`;
  if (process.argv.includes("--check")) {
    if (await readFile(path, "utf8") !== output) throw new Error(`Privacy ${name} schema drift; run pnpm schema:generate`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, output);
  }
  console.log(`Privacy ${name} schema ${process.argv.includes("--check") ? "checked" : "generated"}.`);
}
